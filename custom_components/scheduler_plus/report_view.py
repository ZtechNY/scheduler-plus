"""HTTP view serving Scheduler+ reports as a downloadable PDF.

A dedicated HTTP endpoint rather than a websocket command, since the
websocket API is JSON-only and PDF bytes don't fit that channel.
Registered once via `hass.http.register_view` from `__init__.py`'s
`async_setup` (the same one-time-per-run lifecycle as the websocket
commands - see websocket.py's own registration-timing docstring), and
reuses `report.async_build_report` so the PDF and the on-screen,
websocket-driven report (websocket.py's `generate_report` command) use
the same recorded history. The PDF formats those readings for print.
"""

from __future__ import annotations

import re
from collections.abc import Callable, Iterable
from datetime import date, datetime
from math import isfinite
from typing import Any

from aiohttp import web
from fpdf import FPDF
from fpdf.enums import MethodReturnValue
from homeassistant.components.http import KEY_HASS, HomeAssistantView
from homeassistant.const import UnitOfTemperature
from PIL import Image

from .report import (
    EntityReport,
    ReportData,
    ReportError,
    ReportPoint,
    ReportRangeError,
    async_build_report,
)
from .report_branding import async_get_site_logo, decode_report_logo

# fpdf2 column widths (mm), landscape A4 (297mm) minus 16mm margins each side.
_COLUMN_WIDTHS = (40, 28, 118, 79)
_COLUMN_HEADERS = ("Time", "State", "Details", "Source")
_TABLE_HEADER_HEIGHT = 7.5
_TRUNCATION_NOTE_HEIGHT = 7  # 1mm gap and a 6mm note.
_REPORT_TITLE = "Device Activity Report"
_COVER_LOGO_BOX = (64, 20)
_CONTINUATION_LOGO_BOX = (48, 11)
_COVER_LOGO_GUTTER = 8

# Color palette (RGB 0-255) - a single small set reused throughout, rather
# than picking colors ad hoc per element, so the PDF reads as one design
# instead of a patchwork. Body text is always _TEXT_DARK/_TEXT_MUTED against
# a plain white/near-white row background - state/source get their meaning
# from *text* color, not a colored cell fill, specifically to avoid the bug
# this redesign fixes (a fill color with no matching text-color reset made
# an earlier version's row text invisible - white-on-white/light).
_ACCENT = (14, 148, 190)
_TEXT_DARK = (30, 41, 59)
_TEXT_MUTED = (110, 118, 128)
_HEADER_BG = (30, 41, 59)
_HEADER_TEXT = (255, 255, 255)
_ROW_ALT_BG = (246, 248, 250)
_ROW_BORDER = (224, 228, 232)
_STATE_ACTIVE = (13, 130, 90)  # on/heat/cool/open/playing
_STATE_INACTIVE = (120, 128, 138)  # off/idle/closed
_STATE_OTHER = (178, 110, 15)  # unavailable/unknown/anything else
_SOURCE_RULE = (14, 116, 190)
_SOURCE_OTHER = (140, 148, 158)

_ACTIVE_STATES = {"on", "open", "playing", "heat", "cool", "heat_cool", "auto", "dry", "fan_only"}
_INACTIVE_STATES = {"off", "closed", "idle"}
# Climate mode, not hvac_action: e.g. an idle thermostat in Cool mode
# still has a setpoint, but an Off or Unavailable device does not.
_TARGET_MODES = {"heat", "cool", "heat_cool", "auto"}


def _state_color(state: str) -> tuple[int, int, int]:
    """Which text color communicates a state's meaning at a glance."""
    lowered = state.lower()
    if lowered in _ACTIVE_STATES:
        return _STATE_ACTIVE
    if lowered in _INACTIVE_STATES:
        return _STATE_INACTIVE
    return _STATE_OTHER


class _ReportPdf(FPDF):
    """Draw a scoped logo and a fixed footer without shifting the tables."""

    def __init__(self, logo: Image.Image | None) -> None:
        super().__init__(orientation="L", format="A4")
        self.report_logo = logo

    @property
    def cover_text_width(self) -> float:
        """Keep even wrapped cover text clear of the largest possible logo."""
        return self.epw - (_COVER_LOGO_BOX[0] + _COVER_LOGO_GUTTER if self.report_logo else 0)

    def header(self) -> None:
        """Fit the logo on the right of the title, or in the continuation margin."""
        logo = self.report_logo
        if logo is None:
            return
        first_page = self.page_no() == 1
        max_width, max_height = _COVER_LOGO_BOX if first_page else _CONTINUATION_LOGO_BOX
        scale = min(max_width / logo.width, max_height / logo.height)
        width, height = logo.width * scale, logo.height * scale
        center_y = self.t_margin + 8 if first_page else self.t_margin / 2
        self.image(logo, x=self.w - self.r_margin - width, y=center_y - height / 2,
                   w=width, h=height)

    def footer(self) -> None:
        """Draw the same attribution on every page, including unbranded reports."""
        self.set_y(-12)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(*_TEXT_MUTED)
        self.cell(0, 8, f"Powered by Ztech Solutions  ·  Page {self.page_no()}", align="C")


class SchedulerPlusReportPdfView(HomeAssistantView):
    """Serve a report generated by report.async_build_report as a PDF download."""

    url = "/api/scheduler_plus/report/pdf"
    name = "api:scheduler_plus:report_pdf"
    # requires_auth defaults to True on HomeAssistantView. A plain same-tab
    # navigation/fetch to this URL is NOT enough on its own, despite the
    # browser holding a valid HA session - the frontend (report-card.ts's
    # _downloadPdf) explicitly sends the signed-in user's hass.auth access
    # token as a Bearer header, the same way the rest of Home Assistant's
    # own frontend authenticates its /api/* calls.

    async def get(self, request: web.Request) -> web.Response:
        """Download report data through the existing authenticated endpoint."""
        hass = request.app[KEY_HASS]

        entity_ids = [e for e in request.query.get("entities", "").split(",") if e]
        start_param = request.query.get("start")
        end_param = request.query.get("end")

        if not entity_ids or not start_param or not end_param:
            return web.Response(
                status=400,
                text="entities, start, and end query parameters are required",
            )

        try:
            start_date = date.fromisoformat(start_param)
            end_date = date.fromisoformat(end_param)
        except ValueError:
            return web.Response(status=400, text="start/end must be YYYY-MM-DD")

        try:
            report = await async_build_report(hass, entity_ids, start_date, end_date)
        except ReportRangeError as err:
            return web.Response(status=400, text=str(err))
        except ReportError as err:
            return web.Response(status=503, text=str(err))

        logo = await async_get_site_logo(hass)
        # HA's ClimateEntity publishes both temperature attributes in the
        # configured HA units, not the device's native unit. Do not reconvert.
        temperature_unit = getattr(hass.config.units, "temperature_unit", None)
        pdf_bytes = await hass.async_add_executor_job(
            _render_pdf, report, logo, temperature_unit
        )

        filename = (
            f"scheduler-plus-report-{report.start_date.isoformat()}"
            f"-{report.end_date.isoformat()}.pdf"
        )
        return web.Response(
            body=bytes(pdf_bytes),
            content_type="application/pdf",
            headers={
                "Content-Disposition": f'attachment; filename="{filename}"',
                "Cache-Control": "no-store",
            },
        )


def _safe_text(value: str) -> str:
    """Best-effort latin-1 rendering for fpdf2's core (non-Unicode) fonts.

    fpdf2's built-in Helvetica font only renders latin-1 characters;
    embedding a full Unicode TTF font is out of scope for this table-only
    MVP report. A friendly name outside latin-1 (e.g. Hebrew, common in
    this integration's own userbase given its YidCal-based day conditions/
    time providers) renders with '?' substitutions instead of failing PDF
    generation entirely.
    """
    return value.encode("latin-1", "replace").decode("latin-1")


def _line_count(pdf: FPDF, value: str, width: float) -> int:
    """Estimate wrapped lines so adjacent table rows never overlap."""
    lines = 1
    current = ""
    for word in _safe_text(value).split():
        candidate = f"{current} {word}".strip()
        if current and pdf.get_string_width(candidate) > width - 4:
            lines += 1
            current = word
        else:
            current = candidate
    return lines


def _humanize_word(value: str) -> str:
    """"cool" -> "Cool", "hvac_action" values like "heating" -> "Heating"."""
    spaced = value.replace("_", " ")
    return spaced[:1].upper() + spaced[1:] if spaced else spaced


def _finite_temp(value: object) -> int | float | None:
    """Use only numeric, finite recorder readings (not bools or strings)."""
    if isinstance(value, int) and not isinstance(value, bool):
        return value
    if isinstance(value, float) and isfinite(value):
        return value
    return None


def _active_target(point: ReportPoint | None) -> int | float | None:
    if point is None or point.state not in _TARGET_MODES:
        return None
    return _finite_temp(point.attributes.get("temperature"))


def _format_temp(value: int | float, unit: str) -> str:
    return f"{str(value).removesuffix('.0')}{unit}"


def _format_pdf_date(day: date) -> str:
    """Zero-padded US dates, without changing the date or timezone received."""
    return f"{day.month:02d}/{day.day:02d}/{day.year:04d}"


def _format_pdf_time(at: datetime) -> str:
    """Keep the recorded wall time and 12-hour clock, e.g. 01/02/2026  3:05 PM."""
    return f"{_format_pdf_date(at)}  {at.hour % 12 or 12}:{at:%M %p}"


def _humanize_entity_id(entity_id: str) -> str:
    object_id = entity_id.partition(".")[2] or entity_id
    return " ".join(object_id.replace("_", " ").split()).title() or "Device"


def _entity_reference_formatter(entity_ids: Iterable[str]) -> Callable[[str], str]:
    """Humanize exact known ID tokens, without altering other words or underscores."""
    names = {entity_id.casefold(): _humanize_entity_id(entity_id) for entity_id in entity_ids}
    if not names:
        return lambda text: text
    alternatives = "|".join(re.escape(entity_id) for entity_id in names)
    tokens = re.compile(rf"(?<![\w.])(?:{alternatives})(?!\w|\.\w)", re.IGNORECASE)

    def display_refs(text: str) -> str:
        return tokens.sub(lambda match: names.get(match[0].casefold(), match[0]), text)

    return display_refs


def _entity_labels(
    entities: list[EntityReport], display_refs: Callable[[str], str]
) -> dict[str, str]:
    """Keep friendly names, with a readable and stable suffix only on collisions."""
    labels: dict[str, str] = {}
    for entity in entities:
        friendly = entity.friendly_name.strip() if isinstance(entity.friendly_name, str) else ""
        object_id = entity.entity_id.partition(".")[2]
        if not friendly or ("_" in object_id and friendly.casefold() == object_id):
            friendly = _humanize_entity_id(entity.entity_id)
        labels[entity.entity_id] = _safe_text(display_refs(friendly))

    groups: dict[str, list[str]] = {}
    for entity_id in sorted(labels):
        groups.setdefault(labels[entity_id].casefold(), []).append(entity_id)
    taken = set(groups)
    for ids in groups.values():
        if len(ids) < 2:
            continue
        number = 1
        for entity_id in ids:
            base = labels[entity_id]
            while (label := f"{base} ({number})").casefold() in taken:
                number += 1
            labels[entity_id] = label
            taken.add(label.casefold())
            number += 1
    return labels


def _source_label(point: ReportPoint, display_refs: Callable[[str], str]) -> str:
    """Print the rule (or schedule) as recorded; a nameless match is not 'Other'."""
    if point.source != "rule":
        return "Other"
    for name in (point.rule_name, point.schedule_name):
        if isinstance(name, str) and name.strip():
            return display_refs(name)
    return "Schedule match"


def _describe_attributes(
    domain: str, point: ReportPoint, previous: ReportPoint | None, unit: str
) -> tuple[str, bool]:
    """Format PDF details and flag true changes between adjacent active targets."""
    if domain == "climate":
        parts: list[str] = []
        target = _active_target(point)
        prior_target = _active_target(previous)
        current = _finite_temp(point.attributes.get("current_temperature"))
        action = point.attributes.get("hvac_action")
        changed = False
        if target is not None:
            new_value = _format_temp(target, unit)
            if prior_target is not None and prior_target != target:
                parts.append(f"Target {_format_temp(prior_target, unit)} to {new_value}")
                changed = True
            else:
                parts.append(f"Target {new_value}")
        if current is not None:
            parts.append(f"Room {_format_temp(current, unit)}")
        if isinstance(action, str) and action:
            parts.append(_humanize_word(action))
        return " · ".join(parts), changed
    if domain == "light":
        brightness = point.attributes.get("brightness")
        if isinstance(brightness, (int, float)):
            return f"Brightness {round(brightness / 255 * 100)}%", False
    return "", False


# Per domain, which of a point's tracked attributes count as a "real" change
# worth its own PDF row - as opposed to routine sensor noise (climate's
# current_temperature drifting by a degree every few minutes) that's only
# useful as a continuous line in the on-screen chart, not as a wall of
# near-identical rows. Mirrors frontend/src/report-card.ts's
# LIST_SIGNIFICANT_KEYS - see that constant's docstring for the full
# reasoning. Nothing is filtered for light/switch: their only tracked
# signal already is the meaningful thing.
_LIST_SIGNIFICANT_KEY: dict[str, Callable[[ReportPoint], Any]] = {
    "climate": lambda point: (
        point.state,
        point.attributes.get("temperature"),
        point.attributes.get("hvac_action"),
    ),
}


def _significant_rows(
    points: list[ReportPoint], domain: str
) -> list[tuple[ReportPoint, ReportPoint | None]]:
    """Pair displayed points with their immediately preceding recorded point."""
    key_of = _LIST_SIGNIFICANT_KEY.get(domain)
    kept: list[tuple[ReportPoint, ReportPoint | None]] = []
    last_key: Any = None
    for index, point in enumerate(points):
        if key_of is not None:
            key = key_of(point)
            if kept and key == last_key:
                continue
            last_key = key
        kept.append((point, points[index - 1] if index else None))
    return kept


def _draw_table_header(pdf: FPDF) -> None:
    """Draw the dark column-header row at the current position."""
    pdf.set_fill_color(*_HEADER_BG)
    pdf.set_text_color(*_HEADER_TEXT)
    pdf.set_font("Helvetica", "B", 8.5)
    for width, header in zip(_COLUMN_WIDTHS, _COLUMN_HEADERS):
        pdf.cell(width, _TABLE_HEADER_HEIGHT, header.upper(), fill=True)
    pdf.ln(_TABLE_HEADER_HEIGHT)


def _draw_report_summary(
    pdf: _ReportPdf, sections: list[tuple[EntityReport, list[tuple[ReportPoint, ReportPoint | None]]]]
) -> None:
    """Summarize displayed rows only; a rule match is not a success check."""
    shown = sum(len(rows) for _, rows in sections)
    matched = sum(point.source == "rule" for _, rows in sections for point, _ in rows)
    pdf.set_text_color(*_TEXT_DARK)
    pdf.set_font("Helvetica", "B", 9)
    pdf.multi_cell(
        pdf.cover_text_width, 6,
        f"Devices: {len(sections)}  ·  History rows shown: {shown}  ·  Schedule matches: {matched}",
        align="L", new_x="LMARGIN", new_y="NEXT",
    )
    no_history = sum(entity.no_data for entity, _ in sections)
    truncated = sum(entity.truncated for entity, _ in sections)
    caveats = []
    if no_history:
        caveats.append(f"No history found: {no_history}")
    if truncated:
        caveats.append(f"Truncated histories: {truncated}")
    if caveats:
        pdf.set_text_color(*_TEXT_MUTED)
        pdf.set_font("Helvetica", "", 8.5)
        pdf.cell(0, 5, "  ·  ".join(caveats), new_x="LMARGIN", new_y="NEXT")


def _draw_entity_heading(
    pdf: FPDF, label: str, *, continued: bool = False, measure: bool = False
) -> float:
    """Wrap long device names inside the page margins."""
    pdf.set_text_color(*_TEXT_DARK)
    pdf.set_font("Helvetica", "B", 11 if continued else 13)
    title = label + (" (continued)" if continued else "")
    line_height, gap = (6, 2) if continued else (7, 3)
    if measure:
        return pdf.multi_cell(0, line_height, title, dry_run=True, output=MethodReturnValue.HEIGHT) + gap
    pdf.multi_cell(0, line_height, title, align="L", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(gap)
    return 0


def _layout_row(
    pdf: FPDF, entity: EntityReport, point: ReportPoint, previous: ReportPoint | None,
    unit: str, display_refs: Callable[[str], str],
) -> tuple[tuple[str, ...], tuple[str, ...], float]:
    details, target_changed = _describe_attributes(entity.domain, point, previous, unit)
    values = (
        _format_pdf_time(point.at), _humanize_word(point.state), details,
        _source_label(point, display_refs),
    )
    styles = ("", "B", "B" if target_changed else "", "")
    row_lines = 1
    for width, value, style in zip(_COLUMN_WIDTHS, values, styles):
        pdf.set_font("Helvetica", style, 8.5)
        row_lines = max(row_lines, _line_count(pdf, value, width))
    return values, styles, row_lines * 5 + 2


def _render_pdf(
    report: ReportData, logo: bytes | None = None, temperature_unit: str | None = None
) -> bytearray:
    """Render a clean, readable landscape PDF: hairline row separators and
    color-coded text (not colored cell fills - see this module's palette
    comment for why) rather than a busy full grid, one small header/footer
    per page, and a compact title block up front.
    """
    pdf = _ReportPdf(decode_report_logo(logo) if logo else None)
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(16, 16, 16)
    pdf.set_title(_REPORT_TITLE)
    pdf.add_page()

    pdf.set_text_color(*_TEXT_DARK)
    pdf.set_font("Helvetica", "B", 20)
    pdf.multi_cell(pdf.cover_text_width, 10, _REPORT_TITLE, align="L", new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(*_TEXT_MUTED)
    pdf.set_font("Helvetica", "", 10.5)
    date_range = (
        _format_pdf_date(report.start_date)
        if report.start_date == report.end_date
        else f"{_format_pdf_date(report.start_date)} to {_format_pdf_date(report.end_date)}"
    )
    pdf.multi_cell(pdf.cover_text_width, 6, date_range, align="L", new_x="LMARGIN", new_y="NEXT")
    unit = ""
    if temperature_unit is not None and temperature_unit in (
        UnitOfTemperature.CELSIUS, UnitOfTemperature.FAHRENHEIT,
    ):
        unit = temperature_unit
    sections = [
        (entity, [] if entity.no_data else _significant_rows(entity.points, entity.domain))
        for entity in report.entities
    ]
    _draw_report_summary(pdf, sections)
    if not unit and any(entity.domain == "climate" and rows for entity, rows in sections):
        pdf.set_text_color(*_TEXT_MUTED)
        pdf.set_font("Helvetica", "", 8.5)
        pdf.cell(0, 5, "Temperature units not available", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    pdf.set_draw_color(*_ACCENT)
    pdf.set_line_width(0.8)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(7)

    display_refs = _entity_reference_formatter(entity.entity_id for entity, _ in sections)
    labels = _entity_labels(report.entities, display_refs)
    total_width = sum(_COLUMN_WIDTHS)
    for entity_index, (entity, rows) in enumerate(sections):
        label = labels[entity.entity_id]
        first_row = _layout_row(pdf, entity, *rows[0], unit, display_refs) if rows else None
        content_height = 6 if entity.no_data else _TABLE_HEADER_HEIGHT + (first_row[2] if first_row else 0)
        if entity.truncated and not entity.no_data and len(rows) <= 1:
            content_height += _TRUNCATION_NOTE_HEIGHT
        gap = 7 if entity_index > 0 else 0
        # Measure the actual wrapped friendly heading so it stays with the table
        # header and first row, even when the previous device nearly fills a page.
        if pdf.will_page_break(gap + _draw_entity_heading(pdf, label, measure=True) + content_height):
            pdf.add_page()
        else:
            pdf.ln(gap)
        _draw_entity_heading(pdf, label)

        if entity.no_data:
            pdf.set_text_color(*_TEXT_MUTED)
            pdf.set_font("Helvetica", "I", 9)
            pdf.cell(0, 6, "No data found - may be outside your Home Assistant history retention.",
                     new_x="LMARGIN", new_y="NEXT")
            continue

        _draw_table_header(pdf)

        for index, (point, previous) in enumerate(rows):
            values, styles, row_height = first_row if index == 0 else _layout_row(
                pdf, entity, point, previous, unit, display_refs,
            )
            closing_note = _TRUNCATION_NOTE_HEIGHT if entity.truncated and index == len(rows) - 1 else 0
            if pdf.will_page_break(row_height + closing_note):
                pdf.add_page()
                _draw_entity_heading(pdf, label, continued=True)
                _draw_table_header(pdf)

            x, y = pdf.get_x(), pdf.get_y()
            if index % 2 == 1:
                pdf.set_fill_color(*_ROW_ALT_BG)
                pdf.rect(x, y, total_width, row_height, style="F")

            for column, (width, value) in enumerate(zip(_COLUMN_WIDTHS, values)):
                pdf.set_xy(x, y + 1.2)
                pdf.set_font("Helvetica", styles[column], 8.5)
                if column == 1:
                    pdf.set_text_color(*_state_color(point.state))
                elif column == 3:
                    pdf.set_text_color(*(_SOURCE_RULE if point.source == "rule" else _SOURCE_OTHER))
                else:
                    pdf.set_text_color(*_TEXT_DARK)
                pdf.multi_cell(width, 5, _safe_text(value), border=0, align="L")
                x += width

            pdf.set_draw_color(*_ROW_BORDER)
            pdf.set_line_width(0.2)
            pdf.line(pdf.l_margin, y + row_height, pdf.l_margin + total_width, y + row_height)
            pdf.set_xy(pdf.l_margin, y + row_height)

        if entity.truncated:
            pdf.ln(1)
            pdf.set_text_color(*_TEXT_MUTED)
            pdf.set_font("Helvetica", "I", 8)
            pdf.cell(0, 6, "Truncated - too many changes in this range to list all of them.",
                     new_x="LMARGIN", new_y="NEXT")

    return pdf.output()
